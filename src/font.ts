const GLYPHS = new Map<string, string[]>(
  Object.entries(F).map(([k, v]) => [k, v.split(" ")]),
);

export const GLYPH_W = 6;
export const GLYPH_H = 7;
export const hasGlyph = (ch: string) => GLYPHS.has(ch.toUpperCase());
export const textWidth = (s: string, k = 1) =>
  Math.max(0, s.length * GLYPH_W - 1) * k;

/** Draws `s` with its top-left at (x, y); `k` scales each art pixel. */
export function drawText(
  c: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color: string,
  k = 1,
) {
  c.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS.get(ch) ?? GLYPHS.get("?")!;
    for (let r = 0; r < GLYPH_H; r++)
      for (let q = 0; q < 5; q++)
        if (g[r]![q] === "1")
          c.fillRect(cx + q * k, Math.round(y) + r * k, k, k);
    cx += GLYPH_W * k;
  }
}

/** Calls `fn` for every lit pixel of `s`, for effects that recolour single pixels. */
export function eachTextPixel(s: string, fn: (x: number, y: number) => void) {
  let cx = 0;
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS.get(ch) ?? GLYPHS.get("?")!;
    for (let r = 0; r < GLYPH_H; r++)
      for (let q = 0; q < 5; q++) if (g[r]![q] === "1") fn(cx + q, r);
    cx += GLYPH_W;
  }
}
