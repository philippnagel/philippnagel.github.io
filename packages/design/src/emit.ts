import { ACCENT, FONT, IDENTITY, UI } from "./tokens";

const kebab = (k: string) => k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const vars = (o: Record<string, string>, pad: string) =>
  Object.entries(o)
    .map(([k, v]) => `${pad}--${kebab(k)}: ${v};`)
    .join("\n");

/** The tokens as CSS custom properties, light by default, dark by system setting or `data-theme`. */
export function css() {
  const night = vars(UI.night, "    ");
  return `/* generated by packages/design/scripts/tokens.ts from src/tokens.ts: do not edit */
/* woff2 only: every browser that can run the page reads it */
@font-face {
  font-family: "${FONT.pix}";
  font-style: normal;
  font-display: swap;
  font-weight: 700;
  src: url("@fontsource/pixelify-sans/files/pixelify-sans-latin-700-normal.woff2")
    format("woff2");
}
:root {
${vars({ ...UI.day, ...ACCENT }, "  ")}
  --sans: ${FONT.sans};
  --mono: ${FONT.mono};
  --pix: "${FONT.pix}", var(--sans);
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${night}
  }
}
:root[data-theme="dark"] {
${night.replace(/^ {2}/gm, "")}
}
`;
}

const typ = (v: unknown): string =>
  typeof v === "string"
    ? /^#[0-9a-f]{6}$/i.test(v)
      ? `rgb("${v}")`
      : JSON.stringify(v)
    : `(${Object.entries(v as object)
        .map(([k, x]) => `${kebab(k)}: ${typ(x)}`)
        .join(", ")})`;

/** The tokens as a Typst module: `#import "tokens.typ": identity, accent, ui`. */
export const typst = () =>
  `// generated from packages/design/src/tokens.ts: do not edit
#let identity = ${typ(IDENTITY)}
#let accent = ${typ(ACCENT)}
#let ui = ${typ(UI)}
`;
